#!/usr/bin/env bash
# Phase 1 acceptance checks, run from the admin workstation after `make up && make route`:
#   1. OPNsense is reachable on its WAN (SSH, key auth) and the VPC interfaces are up.
#   2. The test VM on the private subnet got a DHCP lease from OPNsense.
#   3. The test VM reaches the internet through OPNsense NAT (ICMP, DNS, HTTPS).
#   4. From the LAN only what the rules allow gets in: SSH to the test VM works,
#      any other port is silently dropped (timeout, not "connection refused").
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WAN_IP="$(cat "${ROOT}/.cache/host/opnsense-wan.ip" 2>/dev/null || true)"
TEST_MAC="52:54:00:10:01:10"
BASE_SSH=(ssh -o BatchMode=yes -o ConnectTimeout=5 -o LogLevel=ERROR)
# OPNsense: host key is generated by Terraform and pinned (no trust-on-first-use).
OPN_ALIAS="$(terraform -chdir="${ROOT}/terraform/host" output -raw opnsense_host_alias)"
SSH=("${BASE_SSH[@]}" -o StrictHostKeyChecking=yes -o HostKeyAlias="${OPN_ALIAS}"
     -o UserKnownHostsFile="${ROOT}/.cache/host/known_hosts")
# Test VM: throwaway, new host key on every rebuild, only reachable via the lab route.
VM_SSH=("${BASE_SSH[@]}" -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null)

pass=0 fail=0
ok()  { printf '  \033[32mPASS\033[0m %s\n' "$*"; pass=$((pass + 1)); }
bad() { printf '  \033[31mFAIL\033[0m %s\n' "$*"; fail=$((fail + 1)); }
check() { local desc="$1"; shift; if "$@" >/dev/null 2>&1; then ok "${desc}"; else bad "${desc}"; fi; }

[[ -n "${WAN_IP}" ]] || { echo "no OPNsense WAN IP recorded; run make up" >&2; exit 1; }
echo "OPNsense WAN: ${WAN_IP}"

echo "1. firewall"
check "SSH to OPNsense (root, key)" "${SSH[@]}" "root@${WAN_IP}" true
ifaces="$("${SSH[@]}" "root@${WAN_IP}" "sh -c 'ifconfig vtnet1 inet; ifconfig vtnet2 inet; ifconfig vtnet3 inet'" 2>/dev/null)"
for gw in 10.10.1.1 10.10.0.1 10.10.2.1; do
  if grep -q "inet ${gw} " <<<"${ifaces}"; then ok "gateway ${gw} up"; else bad "gateway ${gw} up"; fi
done

echo "2. DHCP"
vm_ip=""
for _ in $(seq 1 24); do
  vm_ip="$("${SSH[@]}" "root@${WAN_IP}" "sh -c 'cat /var/db/dnsmasq.leases'" 2>/dev/null | awk -v m="${TEST_MAC}" '$2==m {print $3}')"
  [[ -n "${vm_ip}" ]] && break
  sleep 5
done
if [[ "${vm_ip}" == 10.10.1.* ]]; then ok "test VM leased ${vm_ip} on the private subnet"; else bad "test VM lease (got '${vm_ip}')"; fi

ip route get 10.10.1.1 2>/dev/null | grep -q "via ${WAN_IP}" || echo "  (no route to 10.10.0.0/16 via ${WAN_IP} on this machine: run make route)"

echo "3. egress via NAT"
VM=("${VM_SSH[@]}" "debian@${vm_ip:-0.0.0.0}")
for _ in $(seq 1 12); do "${VM[@]}" true 2>/dev/null && break; sleep 5; done
check "SSH from LAN to test VM (allowed by rule)" "${VM[@]}" true
check "test VM default route is OPNsense" "${VM[@]}" "ip route | grep -q 'default via 10.10.1.1'"
check "test VM pings 1.1.1.1" "${VM[@]}" "ping -c2 -W3 1.1.1.1"
check "test VM resolves deb.debian.org (Unbound on OPNsense)" "${VM[@]}" "getent hosts deb.debian.org"
check "test VM HTTPS to deb.debian.org" "${VM[@]}" "curl -fsS -m 10 -o /dev/null https://deb.debian.org/"
pub="$("${VM[@]}" "curl -fsS -m 10 https://ifconfig.me" 2>/dev/null)"
[[ -n "${pub}" ]] && echo "  (egress public IP: ${pub})"

echo "4. ingress filtering from the LAN"
# A port nobody listens on: an allowed packet would get an immediate RST ("refused");
# a filtered one just times out.
probe() { timeout 4 bash -c "exec 3<>/dev/tcp/$1/$2" 2>&1; echo "rc=$?"; }
out="$(probe "${vm_ip:-10.10.1.100}" 8080)"
if grep -q "rc=124" <<<"${out}"; then ok "LAN -> test VM :8080 dropped by firewall"; else bad "LAN -> test VM :8080 not filtered (${out//$'\n'/ })"; fi
out="$(probe "${WAN_IP}" 80)"
if grep -q "rc=124" <<<"${out}"; then ok "LAN -> OPNsense :80 dropped"; else bad "LAN -> OPNsense :80 not filtered (${out//$'\n'/ })"; fi
wan_pass="$("${SSH[@]}" "root@${WAN_IP}" "sh -c 'pfctl -sr | grep \"^pass in.* on vtnet0 \" | grep -v bootp'" 2>/dev/null)"
# pfctl prints a /32 as a bare address
admin_re="$(terraform -chdir="${ROOT}/terraform/host" output -json admin_cidrs | python3 -c \
  'import json,sys,re; print("|".join(re.escape(c[:-3] if c.endswith("/32") else c) for c in json.load(sys.stdin)))')"
if [[ -n "${wan_pass}" ]] && ! grep -Evq "from (${admin_re}) " <<<"${wan_pass}"; then
  ok "every WAN pass rule is limited to admin_cidrs ($(wc -l <<<"${wan_pass}") rules)"
else
  bad "WAN pass rules not limited to admin_cidrs:"; echo "${wan_pass}" | sed 's/^/      /'
fi

echo
echo "passed ${pass}, failed ${fail}"
[[ ${fail} -eq 0 ]]
