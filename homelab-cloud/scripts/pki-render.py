#!/usr/bin/env python3
"""Render the lab PKI's PUBLIC material into Git from .cache/ca (ADR 0007). Re-runnable.

Reads only public files and the password-encrypted provisioner key; never the root key or any password.
  k8s/platform/step-ca/config/        ca.json, defaults.json, root + intermediate certs (ConfigMaps
                                      step-ca-config / step-ca-certs, mounted by the step-certificates chart)
  k8s/platform/certificates/step-cluster-issuer.yaml
"""
import base64
import json
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
CA = ROOT / ".cache" / "ca"
OUT = ROOT / "k8s" / "platform" / "step-ca" / "config"
DB_CA = ROOT / "k8s" / "platform" / "databases" / "lab-root-ca.crt"
# Argo CD takes the CA for its OIDC issuer only inline (oidc.config rootCA): kept between these markers
ARGOCD_VALUES = ROOT / "k8s" / "bootstrap" / "argocd" / "values.yaml"
MARK_BEGIN, MARK_END = "# BEGIN lab-root-ca (written by scripts/pki-render.py)", "# END lab-root-ca"
ISSUER = ROOT / "k8s" / "platform" / "certificates" / "step-cluster-issuer.yaml"
NS = "step-ca"
SVC = f"step-ca.{NS}.svc.cluster.local"
GENERATED = "# GENERATED by scripts/pki-render.py from .cache/ca: public material only. Don't edit by hand.\n"


class IndentedDumper(yaml.SafeDumper):
    """Indent block sequences under their key, as the repo's yamllint config expects."""

    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


def dump(data) -> str:
    return yaml.dump(data, Dumper=IndentedDumper, sort_keys=False, width=1000)


def rd(name: str) -> str:
    return (CA / name).read_text()


def main() -> int:
    if not (CA / "root_ca.crt").exists():
        print(f"no PKI in {CA}: run make pki first", file=sys.stderr)
        return 1
    pub = json.loads(rd("provisioner.pub.json"))
    OUT.mkdir(parents=True, exist_ok=True)

    ca_json = {
        "root": "/home/step/certs/root_ca.crt",
        "federateRoots": [],
        "crt": "/home/step/certs/intermediate_ca.crt",
        "key": "/home/step/secrets/intermediate_ca_key",
        "address": "0.0.0.0:9000",
        # only names under the root's name constraint (lab.macpro, cluster.local): step-ca refuses to start
        # with e.g. "step-ca.step-ca.svc" ("not permitted by any constraint")
        "dnsNames": [SVC, "127.0.0.1"],
        "logger": {"format": "json"},
        "db": {"type": "badgerv2", "dataSource": "/home/step/db"},
        "authority": {
            "claims": {
                "minTLSCertDuration": "5m",
                "maxTLSCertDuration": "2160h",
                "defaultTLSCertDuration": "2160h",
                "disableRenewal": False,
            },
            "provisioners": [
                {
                    # cert-manager's way in (step-issuer). The CA serves encryptedKey to clients by design;
                    # it's useless without the provisioner password (SOPS / OpenBao).
                    "type": "JWK",
                    "name": "step-issuer",
                    "key": pub,
                    "encryptedKey": rd("provisioner.encrypted").strip(),
                }
            ],
        },
        "tls": {
            "cipherSuites": [
                "TLS_ECDHE_ECDSA_WITH_CHACHA20_POLY1305",
                "TLS_ECDHE_ECDSA_WITH_AES_128_GCM_SHA256",
                "TLS_AES_128_GCM_SHA256",
            ],
            "minVersion": 1.2,
            "maxVersion": 1.3,
            "renegotiation": False,
        },
    }
    defaults = {
        "ca-url": f"https://{SVC}",
        "ca-config": "/home/step/config/ca.json",
        "root": "/home/step/certs/root_ca.crt",
    }
    (OUT / "ca.json").write_text(json.dumps(ca_json, indent=2) + "\n")
    (OUT / "defaults.json").write_text(json.dumps(defaults, indent=2) + "\n")
    (OUT / "root_ca.crt").write_text(rd("root_ca.crt"))
    (OUT / "intermediate_ca.crt").write_text(rd("intermediate_ca.crt"))
    # a copy for consumers whose kustomization can't reach step-ca/config (load restrictor): CNPG's endpointCA
    # for Garage (s3.lab.macpro, signed by the lab CA; ADR 0010)
    DB_CA.parent.mkdir(parents=True, exist_ok=True)
    DB_CA.write_text(rd("root_ca.crt"))
    # ...and for Argo CD's OIDC issuer (sso.lab.macpro, ADR 0012): replace the PEM between the markers,
    # keeping their indentation
    lines = ARGOCD_VALUES.read_text().splitlines(keepends=True)
    b = next(i for i, l in enumerate(lines) if l.strip() == MARK_BEGIN)
    e = next(i for i, l in enumerate(lines) if l.strip() == MARK_END)
    indent = lines[b][: len(lines[b]) - len(lines[b].lstrip())]
    pem = [indent + l + "\n" for l in rd("root_ca.crt").strip().splitlines()]
    ARGOCD_VALUES.write_text("".join(lines[: b + 1] + pem + lines[e:]))
    (OUT / "kustomization.yaml").write_text(
        "---\n" + GENERATED + dump(
            {
                "apiVersion": "kustomize.config.k8s.io/v1beta1",
                "kind": "Kustomization",
                "namespace": NS,
                # fixed names: the chart mounts step-ca-config / step-ca-certs (existingSecrets mode)
                "generatorOptions": {"disableNameSuffixHash": True},
                "configMapGenerator": [
                    {"name": "step-ca-config", "files": ["ca.json", "defaults.json"]},
                    {"name": "step-ca-certs", "files": ["root_ca.crt", "intermediate_ca.crt"]},
                ],
            }
        )
    )

    issuer = {
        "apiVersion": "certmanager.step.sm/v1beta1",
        "kind": "StepClusterIssuer",
        "metadata": {"name": "step-ca"},
        "spec": {
            "url": f"https://{SVC}",
            "caBundle": base64.b64encode(rd("root_ca.crt").encode()).decode(),
            "provisioner": {
                "name": "step-issuer",
                "kid": pub["kid"],
                "passwordRef": {"name": "step-issuer-provisioner-password", "namespace": NS, "key": "password"},
            },
        },
    }
    ISSUER.write_text("---\n" + GENERATED + dump(issuer))
    print(f"rendered {OUT.relative_to(ROOT)} and {ISSUER.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
